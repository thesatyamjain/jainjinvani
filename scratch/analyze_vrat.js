const existingItems = [];
Object.entries(inv.contentInventory).forEach(([cat, items]) => {
  items.forEach(it => {
    existingItems.push(it);
  });
});

const matched = [];
const unmatched = [];

userItems.forEach(title => {
  const normTitle = title.replace(/[^\u0900-\u097F]/g, '');
  if (!normTitle) return;
  const match = existingItems.find(it => {
    const itNorm = it.title.replace(/[^\u0900-\u097F]/g, '');
    if (!itNorm || itNorm.length < 3) return false;
    return itNorm === normTitle || itNorm.includes(normTitle) || normTitle.includes(itNorm);
  });
  if (match) {
    matched.push({ title, matchedId: match.id, matchedTitle: match.title, cat: match.category });
  } else {
    unmatched.push(title);
  }
});

console.log('User Items Total:', userItems.length);
console.log('Directly matched in inventory:', matched.length);
console.log('Unmatched in inventory:', unmatched.length);
console.log('Matches count:', matched.length);
